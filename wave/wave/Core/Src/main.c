// --- 處理波形輸出的 Timer 中斷 ---
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
    if (htim->Instance == TIM6) {
        uint16_t current_val = 2048; // 預設中心值

        // 根據目前的波形模式，選擇要輸出哪一個陣列的值
        if (wave_mode == 0) {
            current_val = sine_table[wave_index];
        } else if (wave_mode == 1) {
            current_val = triangle_table[wave_index];
        } else if (wave_mode == 2) {
            current_val = square_table[wave_index];
        }

        // 將選定的數值送到 DAC
        HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_1, DAC_ALIGN_12B_R, current_val);

        // 準備下一個點
        wave_index++;
        if (wave_index >= 100) {
            wave_index = 0;
        }
    }
}

// --- 處理按鈕切換的外部中斷 (EXTI) ---
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
    // 判斷是否為 USER 按鈕 (NUCLEO 板子的 USER 鍵對應 PC13)
    if (GPIO_Pin == GPIO_PIN_13) {
        wave_mode++;
        // 若超過 2，則歸零回到正弦波 (正弦->三角->方波->正弦循環)
        if (wave_mode > 2) {
            wave_mode = 0;
        }
    }
}
